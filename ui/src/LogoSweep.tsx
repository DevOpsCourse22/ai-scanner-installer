import { useEffect, useRef } from "react";
import lottie from "lottie-web/build/player/lottie_light";
import data from "./assets/logo-sweep.json";

/** The success moment: the mark writes itself and the highlighter sweeps the
    middle line (generated by scripts/make_logo_lottie.py). Plays once; with
    reduced motion it shows the last frame. */
export default function LogoSweep({ size = 112 }: { size?: number }) {
  const box = useRef<HTMLDivElement>(null);
  useEffect(() => {
    if (!box.current) return;
    const still = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    const anim = lottie.loadAnimation({ container: box.current, renderer: "svg", loop: false,
                                        autoplay: !still, animationData: structuredClone(data) });
    if (still) anim.goToAndStop(anim.totalFrames - 1, true);
    return () => anim.destroy();
  }, []);
  return <div ref={box} className="logo-sweep" style={{ width: size, height: size }} aria-hidden="true" />;
}
